import fs from 'node:fs';
import path from 'node:path';

import {emitApi, emitMsg, emitSets, type Output} from './data.ts';
import {emitFamily} from './family.ts';
import {Imports} from './imports.ts';
import {appMembers, buildModel, mountConst, mountType, type FileName, type Model} from './model.ts';
import {MountEmitter} from './mounts.ts';
import {camel, docText, str} from './names.ts';
import {emitPages} from './pages.ts';

import {cmp} from '../compare.ts';
import {relativeToRoot, type Config} from '../config.ts';
import type {Diagnostic} from '../manifest_types.ts';
import type {SurfaceReport} from '../report_types.ts';

export type GenerateResult = {files: string[]; changed: number; diagnostics: Diagnostic[]};

/**
 * The version of the runtime API (`@mattermost/playwright-lib`'s aria module: `Scope`, `SurfacePage`, the binding
 * types, `apiOp` and `defineApi`, plugin registration) the generated code is written against. Bump it with the
 * runtime's `RUNTIME_API` when generated code changes what it needs from the runtime.
 */
export const GENERATOR_API = 3;

/** Marks a file as the generator's: a later run deletes such a file when it no longer generates it. */
const MARK = 'GENERATED by @mattermost/test-surface';

/**
 * Generates the typed page objects from the surface report (and the i18n catalog for `Msg`). Reads nothing else: the
 * report is the contract between the scan and the generated client. The output is deterministic by construction (keys
 * sorted, fixed layout), so it is written as is.
 */
export function generate(report: SurfaceReport, config: Config): GenerateResult {
    const outDir = config.output.generated;
    if (!outDir) {
        throw new Error('output.generated is not set in the config');
    }
    const diagnostics: Diagnostic[] = [];
    const out: Output = {header: header(config), runtime: runtimeImport(config.output.runtime, outDir)};
    const sources = emitAll(report, out, config, diagnostics);

    const files: string[] = [];
    let changed = 0;
    fs.mkdirSync(outDir, {recursive: true});
    for (const [name, text] of [...sources].sort((a, b) => cmp(a[0], b[0]))) {
        const file = path.join(outDir, name);
        files.push(file);
        if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) {
            fs.writeFileSync(file, text);
            changed++;
        }
    }

    // files a previous run generated that this one didn't
    for (const f of fs.readdirSync(outDir).sort(cmp)) {
        const full = path.join(outDir, f);
        if (!files.includes(full) && (f.endsWith('.ts') || f.endsWith('.json')) && fs.readFileSync(full, 'utf8').includes(MARK)) {
            fs.rmSync(full);
            changed++;
        }
    }
    return {files, changed, diagnostics};
}

/** Every generated file by name, without writing anything. */
export function emitAll(report: SurfaceReport, out: Output, config: Pick<Config, 'i18n'>, diagnostics: Diagnostic[]): Map<string, string> {
    const model = buildModel(report, diagnostics);
    const plugin = report.plugin;
    const mounts = new MountEmitter(model);

    const sources = new Map<string, string>();
    const files = new Set<FileName>([...[...model.families.values()].map((f) => f.file), ...model.scopeFile.values()]);
    for (const file of [...files].sort(cmp)) {
        const imp = new Imports(file, out.runtime);
        const blocks = [
            ...[...model.families.values()].filter((f) => f.file === file).map((f) => emitFamily(model, f, imp)),

            // a child's constant comes before its parent's, which refers to it: a scope sorts after every scope it prefixes
            ...[...model.scopeFile].filter(([, f]) => f === file).map(([s]) => s).sort((a, b) => cmp(b, a)).map((s) => mounts.emitMount(s, imp)),
        ].filter(Boolean);
        const finished = imp.finish(blocks.join('\n\n'));
        sources.set(`${file}.ts`, `${out.header}\n${finished.imports ? `${finished.imports}\n\n` : ''}${finished.body}\n`);
    }

    // a plugin package carries only what it has
    if (!plugin || Object.keys(report.operations).length) {
        sources.set('api.ts', emitApi(report, out));
    }
    if (!plugin || Object.keys(report.sets).length) {
        sources.set('sets.ts', emitSets(report, out));
    }
    if (!plugin) {
        sources.set('pages.ts', emitPages(model, out, diagnostics));
        sources.set('app.ts', emitApp(model, out, diagnostics));
    }
    if (config.i18n && fs.existsSync(config.i18n)) {
        sources.set('msg.ts', emitMsg(config.i18n, out));
    }
    const reexports = [...sources.keys()].map((f) => f.replace(/\.ts$/, '')).sort(cmp).map((m) => `export * from './${m}';`).join('\n');
    sources.set('index.ts', `${out.header}\n${plugin ? pluginIndex(model, out, reexports, diagnostics) : `${apiCheck(out.runtime)}\n${reexports}\n`}`);
    return sources;
}

function emitApp(model: Model, out: Output, diagnostics: Diagnostic[]): string {
    const imp = new Imports('app', out.runtime);
    const {scopes, pages} = appMembers(model, diagnostics);
    const page = imp.page();
    const members = [
        ...scopes.map(({scope, member}) => {
            const f = model.families.get(model.report.scopes[scope].family)!;
            const file = model.scopeFile.get(scope)!;
            const cls = imp.sibling(f.name, f.file);
            const T = `${cls}<${imp.siblingType(mountType(scope), file)}>`;
            return `    /** \`${scope}\` */
    get ${member}(): ${T} {
        return new ${cls}(this.page, ${str(scope)}, ${imp.sibling(mountConst(scope), file)});
    }`;
        }),
        ...pages.map(({page: cls, member}) => `    /** \`${docText(model.report.pages[cls].path)}\` */
    get ${member}(): ${imp.sibling(cls, 'pages')} {
        return new ${cls}(this.page);
    }`),
        `    /** Surfaces of installed plugin test packages (see \`Plugins\`). */
    get plugins(): ${imp.rt('Plugins')} {
        return ${imp.value('pluginSurfaces')}(this.page);
    }`,
    ];
    return `${out.header}
${imp.render()}

/** The webapp, as generated from its testids: \`new App(page).channelHeader.menuButton.click()\`. */
export class App {
    readonly page: ${page};

    constructor(page: ${page}) {
        this.page = page;
    }

${members.join('\n\n')}
}
`;
}

/** Generated code compiles only against a runtime of the API version it was generated for (`RuntimeApiCheck`). */
function apiCheck(runtime: string): string {
    return `import type {RuntimeApiCheck} from '${runtime}';

/** The runtime API these page objects were generated against: they compile only against a runtime of that version. */
export const GENERATOR_API = ${GENERATOR_API};
export type GeneratorApiCheck = RuntimeApiCheck<typeof GENERATOR_API>;
`;
}

/**
 * A plugin package's entry: registers the class of the plugin's scope with the host's `app.plugins`, and adds its type
 * there by declaration merging.
 */
function pluginIndex(model: Model, out: Output, reexports: string, diagnostics: Diagnostic[]): string {
    const plugin = model.report.plugin!;
    const mount = model.report.scopes[plugin.scope];
    const f = mount && model.families.get(mount.family);
    if (!f) {
        diagnostics.push({rule: 'generate', severity: 'error', at: plugin.id, message: `No testids under "${plugin.scope}": nothing to generate for ${plugin.id}.`, fix: `Give the plugin's UI testids under "${plugin.scope}."`});
        return `${reexports}\n`;
    }
    const name = camel(f.name);
    const file = model.scopeFile.get(plugin.scope)!;
    const T = `${f.name}<${mountType(plugin.scope)}>`;
    return `import {registerPluginSurface, type RuntimeApiCheck} from '${out.runtime}';

import {${f.name}} from './${f.file}';
import {${mountConst(plugin.scope)}, type ${mountType(plugin.scope)}} from './${file}';

${reexports}

/** The runtime API this package was generated against: it compiles only against a host runtime of that version. */
export const GENERATOR_API = ${GENERATOR_API};
export type GeneratorApiCheck = RuntimeApiCheck<typeof GENERATOR_API>;

/** \`app.plugins.${name}\`: ${plugin.id}'s UI. */
registerPluginSurface(${str(name)}, (page) => new ${f.name}(page, ${str(plugin.scope)}, ${mountConst(plugin.scope)}));

declare module '${out.runtime}' {
    interface Plugins {
        ${name}: ${T};
    }
}
`;
}

/** Every generated file's header: the report it comes from (relative to the config's root) and how to regenerate it. */
function header(config: Config): string {
    const report = relativeToRoot(config, config.output.report);
    return `// Copyright (c) 2015-present Mattermost, Inc. All Rights Reserved.
// See LICENSE.txt for license information.

// ${MARK} from ${report}. Do not edit.
// Regenerate with \`test-surface generate\`.
`;
}

/** How a file in `outDir` imports the runtime: a package by its name, the runtime's source by a relative path. */
export function runtimeImport(runtime: string, outDir: string): string {
    if (!path.isAbsolute(runtime)) {
        return runtime;
    }
    const rel = path.relative(outDir, runtime).split(path.sep).join('/');
    return rel.startsWith('.') ? rel : `./${rel}`;
}
