import fs from 'node:fs';
import http from 'node:http';
import type {AddressInfo} from 'node:net';
import path from 'node:path';

import {chromium, expect, test} from '@playwright/test';

import {CONTAINMENT_LAUNCH_ARGS, CONTAINMENT_SUMMARY} from './journey_containment.ts';
import {outDir} from './paths.ts';

type Server = {
    server: http.Server;
    origin: string;
    port: number;
    hits: {http: string[]; ws: string[]};
};

async function listen(html: string): Promise<Server> {
    const hits = {http: [] as string[], ws: [] as string[]};
    const server = http.createServer((req, res) => {
        hits.http.push(req.url ?? '');
        res.writeHead(200, {'content-type': 'text/html'});
        res.end(html);
    });
    server.on('upgrade', (req, socket) => {
        hits.ws.push(req.url ?? '');
        socket.destroy();
    });
    await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
    const port = (server.address() as AddressInfo).port;
    return {server, origin: `http://127.0.0.1:${port}`, port, hits};
}

/**
 * Proves what the repo-native-spec containment (Chromium --host-resolver-rules, applied at browser launch in
 * replay-journey mode) actually enforces, and states the residual gap. This is the strongest config-only lever
 * for an UNMODIFIED repo-native spec, which creates its context via the lib (not the Playwright fixtures), so
 * config `use.serviceWorkers`/route handlers cannot reach it.
 */
test('journey containment: host-resolver rules block other hosts; a second loopback port is the residual gap', async () => {
    const allowed = await listen('<html><body>allowed</body></html>');
    const secondLoopback = await listen('<html><body>second 127.0.0.1 origin (other port)</body></html>');

    const browser = await chromium.launch({args: CONTAINMENT_LAUNCH_ARGS});
    const context = await browser.newContext();
    const page = await context.newPage();
    await page.goto(`${allowed.origin}/`);

    const probe = async (url: string) =>
        page.evaluate(
            (u) =>
                fetch(u, {mode: 'no-cors'}).then(
                    () => 'reached',
                    () => 'blocked',
                ),
            url,
        );

    // External host: DNS maps to NOTFOUND -> blocked.
    const externalHost = await probe('http://external.invalid.test/x');
    // "localhost" is not the literal 127.0.0.1 -> NOTFOUND -> blocked.
    const localhostName = await probe(`http://localhost:${allowed.port}/x`);
    // Same allowed origin still works.
    const sameOrigin = await probe(`${allowed.origin}/ok`);
    // Second 127.0.0.1 origin on another port: host resolves (literal 127.0.0.1), port is not filterable -> reachable.
    secondLoopback.hits.http.length = 0;
    const secondPort = await probe(`${secondLoopback.origin}/leak`);

    // WebSocket to the second loopback origin.
    const wsSecond = await page.evaluate(
        (u) =>
            new Promise<string>((resolve) => {
                const ws = new WebSocket(u);
                ws.onopen = () => resolve('reached');
                ws.onerror = () => resolve('blocked');
                ws.onclose = () => resolve('blocked');
            }),
        `${secondLoopback.origin.replace('http', 'ws')}/socket`,
    );
    await page.waitForTimeout(500);

    const secondPortReached = secondPort === 'reached' || secondLoopback.hits.http.length > 0;

    expect(externalHost, 'external host must be blocked').toBe('blocked');
    expect(localhostName, 'localhost (name) must be blocked').toBe('blocked');
    expect(sameOrigin, 'the allowed origin must still work').toBe('reached');

    const report = [
        '# Journey repo-native-spec containment check',
        '',
        'Generated by `explorer-proto/src/cli.ts guard-journey`. Port-free; proves the config-only containment used',
        'by `replay-journey` on the UNMODIFIED repo-native spec.',
        '',
        `- Mechanism: ${CONTAINMENT_SUMMARY}`,
        `- external host (external.invalid.test): ${externalHost}`,
        `- localhost by name (same port as allowed): ${localhostName}`,
        `- same allowed origin: ${sameOrigin}`,
        `- second 127.0.0.1 origin on another port (HTTP): ${secondPort}; server hits: ${secondLoopback.hits.http.length}`,
        `- second 127.0.0.1 origin on another port (WebSocket): ${wsSecond}`,
        '',
        secondPortReached
            ? '- RESIDUAL GAP CONFIRMED: a second 127.0.0.1 origin on a different port is reachable. host-resolver rules cannot filter by port, and the unmodified repo-native spec builds its context via the lib, so no per-request guard can be injected without editing the lib or the spec.'
            : '- A second 127.0.0.1 origin on another port was NOT reached in this run.',
    ];
    fs.mkdirSync(outDir(), {recursive: true});
    fs.writeFileSync(path.join(outDir(), 'guard-journey-report.md'), `${report.join('\n')}\n`);

    await context.close();
    await browser.close();
    allowed.server.close();
    secondLoopback.server.close();
});
