import fs from 'node:fs';
import path from 'node:path';

import {SCRATCH_DIR} from './paths.ts';

export const SCRATCH_SPEC_NAME = 'containment_scratch.spec.ts';

// A plain repo-native-style test: the Playwright \`browser\` fixture (the one the lib's \`pw\` fixture wraps, launched
// with the config's launchOptions) and the lib's TestBrowser create the context, exactly as pw.testBrowser.login does
// minus the REST login. The lib's own \`test\` is not used because its auto fixtures log in to a Mattermost server.
// The local fixture servers and the traffic suite are imported only to drive and count traffic.
const SCRATCH_SPEC = `// Copyright (c) 2015-present Mattermost, Inc. All Rights Reserved.
// See LICENSE.txt for license information.

// Generated by explorer-proto/src/containment_scratch.ts (git-ignored scratch spec). Do not edit.
import fs from 'node:fs';

import {expect, test} from '@playwright/test';
import {TestBrowser} from '@mattermost/playwright-lib';

import {FRAGMENT_SCHEMA, toProbeRecords} from '../../src/containment_report.ts';
import type {RunRecord} from '../../src/containment_report.ts';
import {
    containedFailures,
    controlFailures,
    leakedProbes,
    runSuite,
    startSuiteServers,
    swScriptRequests,
} from '../../src/containment_suite.ts';

const kind = process.env.EXPLORER_SCRATCH_KIND === 'control' ? 'control' : 'contained';
const MUST_LEAK = [
    'second.navigate',
    'second.subresources',
    'second.websocket',
    'second.redirect-cross-origin',
    'localhost.navigate',
    'localhost.websocket',
];

test('plain repo-native test through the thin config (' + kind + ')', async ({browser}) => {
    const testBrowser = new TestBrowser(browser);
    const servers = await startSuiteServers(Number(process.env.EXPLORER_CONTAINMENT_APPROVED_PORT));
    try {
        const {context, page} = await testBrowser.newPage();
        const result = await runSuite(context, page, servers, {externalMapsToSecond: false});
        const secondTotals = {...servers.second.counters};
        await context.close();

        const allowing = await testBrowser.browser.newContext({serviceWorkers: 'allow'});
        const allowingPage = await allowing.newPage();
        await allowingPage.goto(servers.approved.origin + '/ok');
        await allowingPage.evaluate(() => navigator.serviceWorker.register('/explorer-sw-control.js'));
        await new Promise((resolve) => setTimeout(resolve, 1000));
        const swControlRequests = servers.approved.requestPaths.filter((p) => p === '/explorer-sw-control.js').length;
        await allowing.close();
        await new Promise((resolve) => setTimeout(resolve, 500));

        const failures = kind === 'contained' ? containedFailures(result) : controlFailures(result, MUST_LEAK);
        if (swControlRequests < 1) {
            failures.push('service worker positive control: the approved server never saw the worker script request');
        }
        const record: RunRecord = {
            id: 'thin-config-' + kind,
            kind,
            launch: 'explorer-proto/playwright.config.ts (' + kind + ') + lib TestBrowser.newPage()',
            probes: toProbeRecords(result),
            leaked: leakedProbes(result),
            failures,
            secondTotals,
            secondTotalsAfterClose: {...servers.second.counters},
            approvedTotals: {...servers.approved.counters},
            swScriptRequests: swScriptRequests(result),
            swControlRequests,
            proxy: null,
            externalMapsToSecond: false,
            browserVersion: browser.version(),
        };
        fs.writeFileSync(
            process.env.EXPLORER_CONTAINMENT_FRAGMENT as string,
            JSON.stringify({schema: FRAGMENT_SCHEMA, runs: [record]}, null, 2),
        );
        expect(failures).toEqual([]);
    } finally {
        await testBrowser.close();
        await servers.close();
    }
});
`;

/** Writes the scratch spec into the git-ignored infra/.run directory and returns its path. */
export function writeScratchSpec(): string {
    fs.mkdirSync(SCRATCH_DIR, {recursive: true});
    const file = path.join(SCRATCH_DIR, SCRATCH_SPEC_NAME);
    fs.writeFileSync(file, SCRATCH_SPEC);
    return file;
}
