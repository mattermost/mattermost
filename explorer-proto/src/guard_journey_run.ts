import fs from 'node:fs';
import net from 'node:net';
import path from 'node:path';
import type {AddressInfo} from 'node:net';

import {startContainmentProxy} from './containment_proxy.ts';
import {FRAGMENT_SCHEMA, counterLine, readFragment, writeJson} from './containment_report.ts';
import type {Fragment, RunRecord} from './containment_report.ts';
import {writeScratchSpec} from './containment_scratch.ts';
import {EXTERNAL_HOST, isZero} from './containment_suite.ts';
import {CONTAINMENT_SUMMARY, PROXY_PORT_ENV, UNCONTAINED_CONTROL} from './journey_containment.ts';
import {outDir, reportsDir} from './paths.ts';

export type PlaywrightRunner = (mode: string, env?: NodeJS.ProcessEnv) => Promise<number>;

async function freePort(): Promise<number> {
    const server = net.createServer();
    await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
    const {port} = server.address() as AddressInfo;
    await new Promise<void>((resolve) => server.close(() => resolve()));
    return port;
}

const MECHANISM_FILE = 'guard-journey-mechanism.fragment.json';
export const JOURNEY_FRAGMENT_FILE = 'guard-journey.fragment.json';

function probeVerdict(run: RunRecord, name: string, side: 'second' | 'approved'): string {
    const probe = run.probes.find((p) => p.name === name);
    if (!probe) {
        return 'missing';
    }
    const seen = side === 'second' ? !isZero(probe.second) : !isZero(probe.approved) || probe.approvedSawLocalhostHost;
    return seen ? 'reached' : 'blocked';
}

const probeLine = (p: RunRecord['probes'][number]) =>
    `- probe ${p.name}: client ${p.client}; second server +${p.second.connections}c/+${p.second.httpRequests}h/+${p.second.upgrades}u; approved server +${p.approved.connections}c/+${p.approved.httpRequests}h/+${p.approved.upgrades}u`;

function runSection(title: string, run: RunRecord): string[] {
    const lines = [`## ${title}`, '', `- launch: ${run.launch}`];
    if (run.browserVersion) {
        lines.push(`- browser: Chromium ${run.browserVersion}`);
    }
    lines.push(
        `- second server totals while the suite ran: ${counterLine(run.secondTotals)}`,
        `- second server totals after the contexts closed: ${counterLine(run.secondTotalsAfterClose)}`,
        `- approved server totals: ${counterLine(run.approvedTotals)}`,
        `- service worker script requests (default context): ${run.swScriptRequests}${run.swControlRequests === undefined ? '' : `; positive control (serviceWorkers allow): ${run.swControlRequests}`}`,
        `- probes seen by a server that must not see them: ${run.leaked.length === 0 ? 'none' : run.leaked.join(', ')}`,
    );
    if (run.proxy) {
        const p = run.proxy;
        lines.push(
            `- containment proxy: forwarded ${p.allowedHttp} HTTP request(s) and ${p.allowedTunnels + p.allowedUpgrades} tunnel(s) for the approved host:port; refused ${p.refused} (${
                Object.entries(p.refusedByCategory)
                    .sort(([a], [b]) => (a < b ? -1 : 1))
                    .map(([k, n]) => `${k} ${n}`)
                    .join(', ') || 'none'
            }); upstream sockets opened ${p.upstreamSocketsOpened}, approved server connections ${run.approvedTotals.connections}`,
        );
    }
    lines.push(...run.probes.map(probeLine));
    lines.push(`- failures: ${run.failures.length === 0 ? 'none' : run.failures.join('; ')}`, '');
    return lines;
}

function renderReport(mechanism: RunRecord[], spec: RunRecord[]): string {
    const contained = spec.find((r) => r.kind === 'contained');
    const control = spec.find((r) => r.kind === 'control');
    const header = [
        '# Journey repo-native-spec containment check',
        '',
        "Generated by `explorer-proto/src/cli.ts guard-journey`. Port-free. Every verdict is the SECOND server's own",
        "counters (TCP connections accepted, HTTP requests parsed, 'upgrade' events); a client error is only reported,",
        'never used as the verdict. Local loopback fixtures only; no Mattermost stack.',
        '',
        `- Mechanism: ${CONTAINMENT_SUMMARY}`,
    ];
    if (contained) {
        header.push(
            `- external host (${EXTERNAL_HOST}): ${probeVerdict(contained, 'external.navigate', 'second')}`,
            `- localhost by name (same port as allowed): ${probeVerdict(contained, 'localhost.navigate', 'approved')}`,
            `- same allowed origin: ${contained.probes.find((p) => p.name === 'approved.http')?.client === 'status:200' ? 'reached' : 'FAILED'}`,
            `- second 127.0.0.1 origin on another port (HTTP): ${probeVerdict(contained, 'second.navigate', 'second')}; server hits: ${contained.secondTotalsAfterClose.httpRequests}`,
            `- second 127.0.0.1 origin on another port (WebSocket): ${probeVerdict(contained, 'second.websocket', 'second')}; server upgrades: ${contained.secondTotalsAfterClose.upgrades}`,
            `- second 127.0.0.1 origin on another port, all channels: ${counterLine(contained.secondTotalsAfterClose)}`,
        );
    }
    header.push('');
    const sections: string[] = [];
    if (contained) {
        sections.push(...runSection('thin config, spec as run: containment ON (verdict)', contained));
    }
    if (control) {
        sections.push(...runSection('thin config, spec as run: no containment (positive control)', control));
    }
    for (const run of mechanism) {
        sections.push(...runSection(`mechanism ${run.kind}: ${run.id}`, run));
    }
    const notes = [
        '## Direct versus inferred',
        '',
        '- DIRECT: second-origin counters (connections, HTTP requests, upgrades) are read from the second server itself, in the process that owns it.',
        "- DIRECT: for `localhost` by name on the approved port no separate server can exist; the approved server's own counters and `Host` headers show it received nothing for `localhost`.",
        '- DIRECT: the proxy refused each non-approved destination before opening an upstream socket (upstream sockets opened equals the approved server connections accepted).',
        `- INFERRED: the external name \`${EXTERNAL_HOST}\` is refused; when it cannot be mapped to a local server (the thin-config run) the evidence is the proxy's refusal count and the client error. The "proxy only, external name mapped" mechanism run makes it direct: DNS would reach the second server, which still counts 0.`,
        '- INFERRED: a service worker is blocked because no script request reached the approved server, with a positive control in which it is allowed.',
        '- NOT PROVEN: UDP-based channels (WebRTC, WebTransport/QUIC) are outside a TCP proxy; they are not exercised here.',
        '',
    ];
    return `${[...header, ...sections, ...notes].join('\n')}\n`;
}

/** Runs the mechanism check, then the scratch repo-native spec through the thin config, with and without containment. */
export async function runGuardJourney(playwright: PlaywrightRunner): Promise<number> {
    const reports = reportsDir();
    fs.mkdirSync(reports, {recursive: true});
    const mechanismFile = path.join(reports, MECHANISM_FILE);
    fs.rmSync(mechanismFile, {force: true});
    let failed = (await playwright('guard-journey')) !== 0;

    writeScratchSpec();
    const specRuns: RunRecord[] = [];
    for (const kind of ['contained', 'control'] as const) {
        const approvedPort = await freePort();
        const proxy =
            kind === 'contained'
                ? await startContainmentProxy({
                      host: '127.0.0.1',
                      port: approvedPort,
                  })
                : null;
        const fragmentFile = path.join(reports, `guard-journey-spec-${kind}.fragment.json`);
        fs.rmSync(fragmentFile, {force: true});
        let status: number;
        try {
            status = await playwright('guard-journey-spec', {
                [PROXY_PORT_ENV]: proxy ? String(proxy.port) : UNCONTAINED_CONTROL,
                EXPLORER_CONTAINMENT_APPROVED_PORT: String(approvedPort),
                EXPLORER_CONTAINMENT_FRAGMENT: fragmentFile,
                EXPLORER_SCRATCH_KIND: kind,
            });
        } finally {
            await proxy?.close();
        }
        if (status !== 0 || !fs.existsSync(fragmentFile)) {
            failed = true;
        }
        if (!fs.existsSync(fragmentFile)) {
            continue;
        }
        const [run] = readFragment(fragmentFile).runs;
        if (proxy) {
            run.proxy = {...proxy.stats};
            if (proxy.stats.upstreamSocketsOpened !== run.approvedTotals.connections) {
                run.failures.push(
                    `proxy opened ${proxy.stats.upstreamSocketsOpened} upstream sockets, approved server accepted ${run.approvedTotals.connections}`,
                );
            }
            if (proxy.stats.refused === 0) {
                run.failures.push('the proxy refused nothing: it was not in the request path');
            }
            failed ||= run.failures.length > 0;
        }
        specRuns.push(run);
    }

    const mechanism = fs.existsSync(mechanismFile) ? readFragment(mechanismFile).runs : [];
    failed ||= mechanism.length === 0 || mechanism.some((r) => r.failures.length > 0);
    const combined: Fragment = {
        schema: FRAGMENT_SCHEMA,
        runs: [...specRuns, ...mechanism],
    };
    writeJson(path.join(reports, JOURNEY_FRAGMENT_FILE), combined);
    fs.mkdirSync(outDir(), {recursive: true});
    fs.writeFileSync(path.join(outDir(), 'guard-journey-report.md'), renderReport(mechanism, specRuns));

    for (const run of [...specRuns, ...mechanism]) {
        process.stdout.write(
            `guard-journey ${run.id}: second server ${counterLine(run.secondTotalsAfterClose)}; approved server ${counterLine(run.approvedTotals)}; failures ${run.failures.length}\n`,
        );
    }
    process.stdout.write(`guard-journey: ${failed ? 'FAIL' : 'PASS'}\n`);
    return failed ? 1 : 0;
}
