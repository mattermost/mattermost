import fs from 'node:fs';
import http from 'node:http';
import type {AddressInfo} from 'node:net';
import path from 'node:path';

import {expect, test} from '@playwright/test';

import {GuardLedger, closeGuardedContext, guardedBrowser} from './guard.ts';
import {outDir} from './paths.ts';

const ITERATIONS = 40;
const REQUESTS_PER_ITERATION = 48;

let server: http.Server;
let origin: string;
const outcomes: Array<{iteration: number; teardownAborted: number; violations: string[]}> = [];

// Staggered, streamed responses so that, at close time, some handlers are still fetching and others
// hold a fetched response they are about to fulfil.
test.beforeAll(async () => {
    server = http.createServer((req, res) => {
        const url = new URL(req.url ?? '/', 'http://stand-in');
        if (url.pathname !== '/slow') {
            res.writeHead(200, {'content-type': 'text/html'});
            res.end('<html><body>race stand-in</body></html>');
            return;
        }
        const n = Number(url.searchParams.get('n') ?? 0);
        const delay = (n * 37) % 240;
        res.writeHead(200, {'content-type': 'text/plain'});
        setTimeout(() => {
            res.write('x'.repeat(2048));
            setTimeout(() => res.end('done'), 20);
        }, delay);
    });
    await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
    origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
});

test.afterAll(async () => {
    server?.closeAllConnections();
    server?.close();
    const failed = outcomes.filter((o) => o.violations.length > 0);
    const body = [
        '# Guard teardown race check',
        '',
        'Generated by `explorer-proto/src/cli.ts guard-race`. Local stand-in allowed origin (not Mattermost).',
        '',
        `- iterations completed: ${outcomes.length} of ${ITERATIONS}`,
        `- iterations with unexpected handler errors: ${failed.length}`,
        `- teardown_aborted (benign, teardown-caused) across iterations: ${outcomes.reduce((s, o) => s + o.teardownAborted, 0)}`,
        ...failed.map((o) => `- iteration ${o.iteration}: ${o.violations.join('; ')}`),
    ];
    fs.mkdirSync(outDir(), {recursive: true});
    fs.writeFileSync(path.join(outDir(), 'guard-race-report.md'), `${body.join('\n')}\n`);
});

for (let iteration = 0; iteration < ITERATIONS; iteration++) {
    test(`guard survives closing with ${REQUESTS_PER_ITERATION} same-origin requests in flight #${iteration}`, async ({
        browser,
    }) => {
        const ledger = new GuardLedger('replay');
        const context = await guardedBrowser(browser, origin, ledger).newContext();
        const page = await context.newPage();
        await page.goto(`${origin}/page`);

        await page.evaluate((count) => {
            for (let n = 0; n < count; n++) {
                if (n % 2 === 0) {
                    fetch(`/slow?n=${n}`).catch(() => undefined);
                } else {
                    const img = new Image();
                    img.src = `/slow?n=${n}`;
                }
            }
        }, REQUESTS_PER_ITERATION);

        // Close at a different point of the response schedule on every iteration.
        await page.waitForTimeout(40 + ((iteration * 23) % 200));
        await closeGuardedContext(context, ledger);
        // Give any late handler rejection a chance to surface inside this test.
        await new Promise((resolve) => setTimeout(resolve, 300));

        outcomes.push({iteration, teardownAborted: ledger.teardownAborted ?? 0, violations: [...ledger.violations]});
        expect(ledger.violations).toEqual([]);
    });
}

test('teardown messages are benign only while the session is closing', () => {
    const ledger = new GuardLedger('replay');
    const disposed = new Error('route.fulfill: Fetch response has been disposed');
    expect(ledger.isTeardownError(disposed)).toBe(false);
    ledger.closing = true;
    expect(ledger.isTeardownError(disposed)).toBe(true);
    expect(ledger.isTeardownError(new Error('route.fulfill: Request context disposed'))).toBe(true);
    expect(ledger.isTeardownError(new Error('route.fetch: net::ERR_CONNECTION_REFUSED'))).toBe(false);
});
