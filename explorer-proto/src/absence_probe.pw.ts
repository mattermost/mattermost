import fs from 'node:fs';
import path from 'node:path';

import type {Locator} from '@playwright/test';
import {expect, test} from '@mattermost/playwright-lib';

import {SCOPE, absenceAssertions, absenceLocator} from './assertions.ts';
import type {AbsenceAssertion} from './assertions.ts';
import {readManifest} from './manifest.ts';
import {outDir} from './paths.ts';
import {parseStep, readScenarios, startPath} from './scenarios.ts';
import {closeGuardedSession, closeGuardedSessions, openGuardedSession} from './session.ts';

test.afterEach(closeGuardedSessions);

function locatorFor(info: Locator, a: {role: string; name: string; match: AbsenceAssertion['match']}): Locator {
    const role = a.role as 'button';
    return a.match === 'contains'
        ? info.getByRole(role, {name: new RegExp(a.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))})
        : info.getByRole(role, {name: a.name, exact: true});
}

function describeLocator(a: {role: string; name: string; match: AbsenceAssertion['match']}): string {
    return a.match === 'contains'
        ? `getByRole('${a.role}', {name: /${a.name}/})`
        : `getByRole('${a.role}', {name: '${a.name}', exact: true})`;
}

/**
 * Non-vacuity proof for the declared absence checks. On the no-archive seed each locator must find the
 * element it claims is absent on the archived seed; on an archived seed each must find nothing.
 */
for (const scenario of readScenarios().filter((s) => absenceAssertions(s).length > 0)) {
    test(`absence locators of ${scenario.id} detect presence and absence`, {tag: ['@explorer_pilot']}, async ({pw}) => {
        const {variant} = readManifest();
        const expectPresent = variant === 'no-archive';
        const session = await openGuardedSession(pw);
        const {page, channelsPage} = session;
        const info = page.getByRole(SCOPE.role as 'region', {name: SCOPE.name, exact: true});

        const [team, , channel] = startPath(scenario).split('/').slice(1);
        await channelsPage.goto(team, channel);
        await channelsPage.centerView.header.toBeVisible();
        for (const raw of scenario.reachable_path.slice(1)) {
            const step = parseStep(raw);
            if (step.kind === 'click') {
                await page.getByRole(step.role as 'button', {name: step.name, exact: true}).click();
            }
        }
        await expect(info).toBeVisible();
        await expect(info.getByRole('button', {name: 'Members', exact: true})).toBeVisible();

        const lines: string[] = [];
        const failures: string[] = [];
        for (const a of absenceAssertions(scenario)) {
            const entry = absenceLocator(scenario, a);
            const locator = locatorFor(info, a);
            if (expectPresent) {
                await expect(locator.first())
                    .toBeAttached({timeout: 5000})
                    .catch(() => undefined);
            }
            const count = await locator.count();
            let verdict: string;
            if (!expectPresent) {
                verdict = count === 0 ? 'PASS (absent as declared)' : 'FAIL (present on the archived seed)';
            } else if (count >= 1) {
                verdict = 'PASS (locator detects the element when present)';
            } else if (entry.source_ref) {
                verdict = `NOT SHOWN PRESENT by this probe: qa-user is a regular member and ${a.name} needs manage_team; presence of this exact name is exercised by the verify control with qa-user as team admin (source: ${entry.source_ref})`;
            } else {
                verdict = 'FAIL (locator found nothing although the element should be present: vacuous)';
            }
            if (verdict.startsWith('FAIL')) {
                failures.push(`${describeLocator(a)}: ${verdict}`);
            }
            lines.push(`- region 'Info' ${describeLocator(a)}: count ${count}: ${verdict}`);
            if (a.match === 'contains') {
                const exactCount = await locatorFor(info, {...a, match: 'exact'}).count();
                lines.push(
                    `  - for comparison, the exact-name form ${describeLocator({...a, match: 'exact'})}: count ${exactCount}`,
                );
            }
        }

        fs.mkdirSync(outDir(), {recursive: true});
        const body = [
            `# Absence probe: ${scenario.id} on seed variant ${variant}`,
            '',
            'Generated by `explorer-proto/src/cli.ts probe-absence`. Not part of the pilot specs.',
            `Expectation on this variant: every absence locator ${expectPresent ? 'finds >= 1 element' : 'finds 0 elements'} inside region 'Info'.`,
            '',
            ...lines,
        ];
        fs.writeFileSync(path.join(outDir(), `absence-probe-${variant}.md`), `${body.join('\n')}\n`);
        await closeGuardedSession(session);
        expect(failures).toEqual([]);
    });
}
