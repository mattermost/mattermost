import {outDir, reportsDir} from './paths.ts';

// Runs entirely on loopback fixtures (an approved origin with a WebSocket echo, and a second origin whose
// own counters are the evidence). No Mattermost stack is needed. Verdicts never come from a client error.

const MAP_EXTERNAL = `--host-resolver-rules=MAP ${EXTERNAL_HOST} 127.0.0.1`;
const report: string[] = [];
const runs: RunRecord[] = [];

test.afterAll(() => {
    fs.mkdirSync(outDir(), {recursive: true});
    const body = [
        '# Network guard check',
        '',
        'Generated by `explorer-proto/src/cli.ts guard-check`. Port-free. Local loopback fixtures: an approved origin',
        "(HTTP + WebSocket echo) and a second origin. Every verdict is the second server's own counters (TCP connections",
        "accepted, HTTP requests parsed, 'upgrade' events), not a client error.",
        '',
        ...report,
    ];
    fs.writeFileSync(path.join(outDir(), 'guard-report.md'), `${body.join('\n')}\n`);
    const fragment: Fragment = {schema: FRAGMENT_SCHEMA, runs};
    writeJson(path.join(reportsDir(), 'guard-check.fragment.json'), fragment);
});

async function guardedRun(browser: Browser, mode: 'exploration' | 'replay', approvedPort?: number) {
    const servers = await startSuiteServers(approvedPort);
    const ledger = new GuardLedger(mode);
    const testBrowser = new TestBrowser(guardedBrowser(browser, servers.approved.origin, ledger));
    try {
        const {context, page} = await testBrowser.newPage();
        const result = await runSuite(context, page, servers, {
            externalMapsToSecond: true,
        });
        const totals = {...servers.second.counters};
        const violationsBefore = [...ledger.violations];
        const foreign = foreignPageOrigins(context, servers.approved.origin);
        await closeWithGuard(ledger, () => testBrowser.close());
        await new Promise((resolve) => setTimeout(resolve, 500));
        return {servers, ledger, result, totals, violationsBefore, foreign};
    } catch (error) {
        await testBrowser.close().catch(() => undefined);
        await servers.close();
        throw error;
    }
}

for (const mode of ['exploration', 'replay'] as const) {
    test(`guard rejects other origins in ${mode} mode`, {tag: ['@explorer_pilot']}, async () => {
        const browser = await chromium.launch({
            args: [WS_LNA_LAUNCH_ARG, MAP_EXTERNAL],
        });
        try {
            const {servers, ledger, result, totals, violationsBefore, foreign} = await guardedRun(browser, mode);
            const failures = containedFailures(result);
            const afterClose = {...servers.second.counters};
            try {
                expect(failures).toEqual([]);
                expect(totals).toEqual({
                    connections: 0,
                    httpRequests: 0,
                    upgrades: 0,
                });
                expect(afterClose).toEqual({
                    connections: 0,
                    httpRequests: 0,
                    upgrades: 0,
                });
                expect(violationsBefore).toEqual([]);
                expect(ledger.violations).toEqual([]);
                expect(foreign).toEqual([]);
            } finally {
                runs.push({
                    id: mode,
                    kind: 'contained',
                    launch: `guardedBrowser (${mode}) via TestBrowser.newPage on a loopback fixture`,
                    probes: toProbeRecords(result),
                    leaked: leakedProbes(result),
                    failures,
                    secondTotals: totals,
                    secondTotalsAfterClose: afterClose,
                    approvedTotals: {...servers.approved.counters},
                    swScriptRequests: swScriptRequests(result),
                    proxy: null,
                    externalMapsToSecond: true,
                    violations: violationsBefore.length,
                    violationsAfterClose: ledger.violations.length,
                });
                report.push(`## ${mode} mode (guardedBrowser via TestBrowser.newPage on a loopback fixture)`, '');
                report.push(...renderProbes(result));
                report.push(
                    `- service worker register(): ${result.probes.find((p) => p.name === 'service-worker.register')?.client}; script requests seen: ${swScriptRequests(result)}`,
                );
                report.push(
                    `- second server hits: http ${totals.httpRequests}, websocket upgrades ${totals.upgrades}, connections ${totals.connections}`,
                );
                report.push(`- violations: ${violationsBefore.length}`);
                report.push(...Object.entries(ledger.summary()).map(([k, n]) => `- blocked ${k}: ${n}`));
                report.push(`- violations after close: ${ledger.violations.length}`);
                report.push(`- teardown_aborted (benign, teardown-caused): ${ledger.teardownAborted}`, '');
                await servers.close();
            }
        } finally {
            await browser.close();
        }
    });
}

test('positive control: the same traffic in an unguarded browser reaches the second server', async () => {
    const servers = await startSuiteServers();
    const browser = await chromium.launch({args: [MAP_EXTERNAL]});
    try {
        const context = await browser.newContext({serviceWorkers: 'allow'});
        const page = await context.newPage();
        const result = await runSuite(context, page, servers, {
            externalMapsToSecond: true,
        });
        const totals = {...servers.second.counters};
        await context.close();
        const expected = [
            'second.navigate',
            'second.subresources',
            'second.websocket',
            'second.redirect-cross-origin',
            'second.redirect-chain',
            'localhost.navigate',
            'localhost.websocket',
            'external.navigate',
            'external.websocket',
            'service-worker.register',
        ];
        const failures = controlFailures(result, expected);
        runs.push({
            id: 'control-unguarded',
            kind: 'control',
            launch: 'plain Chromium launch, no guard (external name mapped to the second server)',
            probes: toProbeRecords(result),
            leaked: leakedProbes(result),
            failures,
            secondTotals: totals,
            secondTotalsAfterClose: {...servers.second.counters},
            approvedTotals: {...servers.approved.counters},
            swScriptRequests: swScriptRequests(result),
            proxy: null,
            externalMapsToSecond: true,
        });
        report.push('## positive control (no guard; proves the second server can observe each channel)', '');
        report.push(...renderProbes(result));
        report.push(`- second server totals: ${counterLine(totals)}`);
        report.push(`- probes seen by a server that must not see them: ${leakedProbes(result).join(', ')}`, '');
        expect(failures).toEqual([]);
    } finally {
        await browser.close();
        await servers.close();
    }
});

test('approved-origin WebSocket completes under the guard (Local Network Access)', async ({browser}) => {
    const outcomes: string[] = [];
    const attempt = async (label: string, target: Browser, guarded: boolean) => {
        const servers = await startSuiteServers();
        const ledger = new GuardLedger('replay');
        const testBrowser = new TestBrowser(guarded ? guardedBrowser(target, servers.approved.origin, ledger) : target);
        try {
            const {page} = await testBrowser.newPage();
            const consoleErrors: string[] = [];
            page.on('console', (m) => m.type() === 'error' && consoleErrors.push(m.text()));
            await page.goto(`${servers.approved.origin}/ok`);
            const echo = await page.evaluate(pageWebSocketEcho, {
                url: `ws://127.0.0.1:${servers.approved.port}/ws`,
                message: 'lna-echo',
            });
            const lna = consoleErrors.some((e) => e.includes('ERR_BLOCKED_BY_LOCAL_NETWORK_ACCESS_CHECKS'));
            outcomes.push(
                `- ${label}: ${echo}; approved server upgrades ${servers.approved.counters.upgrades}; LNA block seen: ${lna}`,
            );
            return {echo, upgrades: servers.approved.counters.upgrades};
        } finally {
            await testBrowser.close();
            await servers.close();
        }
    };

    const configured = await attempt('guard, browser from playwright.config.ts launchOptions', browser, true);
    // Explicit empty args: launches inside a test otherwise inherit the config's launchOptions, workaround included.
    const without = await chromium.launch({args: []});
    const withoutFlag = await attempt('guard, plain launch without the workaround flag (diagnostic)', without, true);
    const noGuard = await attempt('no guard, plain launch (diagnostic)', without, false);
    await without.close();

    report.push('## approved-origin WebSocket under the guard (Local Network Access)', '');
    report.push(...outcomes, '');
    expect(configured).toEqual({echo: 'ws:echo:lna-echo', upgrades: 1});
    expect(noGuard.echo).toBe('ws:echo:lna-echo');
    // The diagnostic is reported, not asserted: it documents the browser behaviour the workaround exists for.
    expect(['ws:echo:lna-echo', 'ws:failed']).toContain(withoutFlag.echo);
});
