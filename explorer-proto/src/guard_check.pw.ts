/** Navigates a throwaway page of the same context, so a blocked attempt's error page cannot race later steps. */
async function attemptNavigation(context: BrowserContext, url: string): Promise<{outcome: string; finalPath: string}> {
    const page = await context.newPage();
    try {
        await page.goto(url, {timeout: 10_000});
        return {outcome: 'loaded', finalPath: new URL(page.url()).pathname};
    } catch (error) {
        return {outcome: /ERR_BLOCKED_BY_CLIENT/.test(String(error)) ? 'blocked' : 'failed', finalPath: ''};
    } finally {
        await page.close();
    }
}

async function inPageAttempts(page: Page, httpTargets: string[], wsTargets: string[]) {
    return page.evaluate(
        async ({httpTargets, wsTargets}) => {
            const results: string[] = [];
            for (const url of httpTargets) {
                results.push(
                    await fetch(url, {mode: 'no-cors'}).then(
                        () => 'fetch:loaded',
                        () => 'fetch:failed',
                    ),
                );
                results.push(
                    await new Promise<string>((resolve) => {
                        const img = new Image();
                        img.onload = () => resolve('image:loaded');
                        img.onerror = () => resolve('image:failed');
                        img.src = `${url}?img`;
                    }),
                );
                const frame = document.createElement('iframe');
                frame.src = `${url}?frame`;
                document.body.appendChild(frame);
            }
            for (const url of wsTargets) {
                results.push(
                    await new Promise<string>((resolve) => {
                        const ws = new WebSocket(url);
                        ws.onopen = () => resolve('ws:open');
                        ws.onerror = () => resolve('ws:failed');
                        ws.onclose = () => resolve('ws:failed');
                    }),
                );
            }
            await new Promise((resolve) => setTimeout(resolve, 1500));
            return results;
        },
        {httpTargets, wsTargets},
    );
}

for (const mode of ['exploration', 'replay'] as const) {
    test(`guard rejects other origins in ${mode} mode`, {tag: ['@explorer_pilot']}, async ({pw}) => {
        const origin = allowedOrigin();
        const port = new URL(origin).port;
        const localhostSamePort = `http://localhost:${port}`;
        second.hits.http.length = 0;
        second.hits.upgrades.length = 0;

        const session = await openGuardedSession(pw, mode);
        const {page, channelsPage, context, ledger} = session;
        const allowedSockets: string[] = [];
        page.on('websocket', (ws) => allowedSockets.push(classifyTarget(ws.url(), origin)));
        const swProbeRequests: string[] = [];
        context.on('request', (r) => r.url().includes('explorer-sw-probe') && swProbeRequests.push(r.url()));

        // * The allowed origin still works: the app loads and its own WebSocket connects
        await channelsPage.goto('qa-team', 'qa-sandbox');
        await channelsPage.toBeVisible();
        await expect.poll(() => allowedSockets.includes('allowed')).toBe(true);

        // * Top-level navigation to a second localhost origin and to localhost on the same port is rejected
        expect((await attemptNavigation(context, `${second.origin}/navigate`)).outcome).toBe('blocked');
        expect((await attemptNavigation(context, `${localhostSamePort}/qa-team/channels/qa-sandbox`)).outcome).toBe(
            'blocked',
        );

        // * Subresources and WebSockets to those origins fail from inside the app
        const results = await inPageAttempts(
            page,
            [`${second.origin}/subresource`, `${localhostSamePort}/api/v4/system/ping`],
            [
                `${second.origin.replace('http', 'ws')}/socket`,
                `${localhostSamePort.replace('http', 'ws')}/api/v4/websocket`,
            ],
        );
        expect(results.every((r) => r.endsWith(':failed'))).toBe(true);

        // * Service workers are blocked: registering one never even requests its script
        const sw = await page.evaluate(() =>
            navigator.serviceWorker.register('/explorer-sw-probe.js').then(
                () => 'registered',
                () => 'rejected',
            ),
        );
        await page.waitForTimeout(1000);
        expect(swProbeRequests).toEqual([]);

        // * Nothing reached the second server, nothing escaped, and the page stayed on the allowed origin
        expect(second.hits).toEqual({http: [], upgrades: []});
        expect(ledger.violations).toEqual([]);
        expect(foreignPageOrigins(context, origin)).toEqual([]);

        report.push(`## ${mode} mode (openGuardedSession -> TestBrowser.login on the guarded browser)`, '');
        report.push(
            '- navigation to second 127.0.0.1 origin: blocked; navigation to localhost on the same port: blocked',
        );
        report.push(`- in-page attempts: ${results.join(', ')}`);
        report.push(`- service worker register(): ${sw}; script requests seen: ${swProbeRequests.length}`);
        report.push(
            `- second server hits: http ${second.hits.http.length}, websocket upgrades ${second.hits.upgrades.length}`,
        );
        report.push(`- violations: ${ledger.violations.length}`);
        report.push(...Object.entries(ledger.summary()).map(([k, n]) => `- blocked ${k}: ${n}`), '');
        await closeGuardedSession(session);
    });
}

test(
    'guard aborts redirects to another origin and keeps same-origin redirects',
    {tag: ['@explorer_pilot']},
    async ({pw}) => {
        second.hits.http.length = 0;
        const results: Record<string, string> = {};

        // Positive control: an unguarded context does follow the cross-origin redirect and registers a worker.
        const control = await pw.testBrowser.browser.newContext({serviceWorkers: 'allow'});
        const controlPage = await control.newPage();
        await controlPage.goto(`${standIn.origin}/redirect-cross`);
        results.control_redirect = classifyTarget(controlPage.url(), standIn.origin);
        await controlPage.goto(`${standIn.origin}/ok`);
        results.control_sw = await controlPage.evaluate(() =>
            navigator.serviceWorker.register('/sw.js').then(
                () => 'registered',
                (e) => `rejected ${e}`,
            ),
        );
        await expect.poll(() => standIn.hits.http.includes('/sw.js'), {message: results.control_sw}).toBe(true);
        await control.close();
        expect(second.hits.http).toEqual(['/redirect-target']);

        second.hits.http.length = 0;
        standIn.hits.http.length = 0;
        const ledger = new GuardLedger('exploration');
        const context = await guardedBrowser(pw.testBrowser.browser, standIn.origin, ledger).newContext();
        const page = await context.newPage();

        results.direct_cross = (await attemptNavigation(context, `${standIn.origin}/redirect-cross`)).outcome;
        results.chain_same_then_cross = (await attemptNavigation(context, `${standIn.origin}/redirect-chain`)).outcome;
        const same = await attemptNavigation(context, `${standIn.origin}/redirect-same`);
        results.same_origin = same.outcome;
        results.same_origin_final = same.finalPath;
        await page.goto(`${standIn.origin}/ok`);
        results.fetch_cross = await page.evaluate(
            (url) =>
                fetch(url).then(
                    () => 'loaded',
                    () => 'failed',
                ),
            `${standIn.origin}/redirect-cross`,
        );
        await page.evaluate(() => navigator.serviceWorker.register('/sw.js').catch(() => undefined));
        await page.waitForTimeout(1000);
        results.sw_script_requested = String(standIn.hits.http.includes('/sw.js'));

        expect(results).toEqual({
            control_redirect: 'same-host-other-port',
            control_sw: 'registered',
            direct_cross: 'blocked',
            chain_same_then_cross: 'blocked',
            same_origin: 'loaded',
            same_origin_final: '/ok',
            fetch_cross: 'failed',
            sw_script_requested: 'false',
        });
        expect(second.hits.http).toEqual([]);
        expect(ledger.violations).toEqual([]);
        expect(foreignPageOrigins(context, standIn.origin)).toEqual([]);
        await context.close();

        report.push('## redirects (guardedBrowser with a local stand-in allowed origin)', '');
        report.push(...Object.entries(results).map(([k, v]) => `- ${k}: ${v}`));
        report.push(
            `- second server hits while guarded: ${second.hits.http.length}`,
            `- violations: ${ledger.violations.length}`,
        );
        report.push(...Object.entries(summarize(ledger.blocked)).map(([k, n]) => `- blocked ${k}: ${n}`), '');
    },
);
