import fs from 'node:fs';
import path from 'node:path';

import {describe} from './snapshot.ts';
import type {RoleName} from './snapshot.ts';

export const TRACE_SCHEMA = 'explorer-trace/v1';

export type Skipped = RoleName & {reason: string};

export type TraceState = {
    id: string;
    depth: number;
    root: string;
    pathname: string;
    via: RoleName[];
    candidates: RoleName[];
    skipped: Skipped[];
    allowlistedAbsent: RoleName[];
    roleNames: Array<RoleName & {count: number}>;
    snapshot: string;
};

export type TraceTransition = {
    n: number;
    from: string;
    action: RoleName;
    to: string;
    changes: string[];
    note?: string;
};

export type EmissionRecord = {
    scenario: string;
    status: 'emitted' | 'stopped' | 'deduped';
    file?: string;
    path?: string[];
    reasons: string[];
    locatorChecks: string[];
};

export type Trace = {
    schema: string;
    allowlist: RoleName[];
    budget: {
        limits: {maxActions: number; maxDepth: number; maxStates: number};
        used: {actions: number; states: number; deepest: number; budgetSkips: number};
    };
    roots: Array<{path: string; state: string}>;
    states: TraceState[];
    transitions: TraceTransition[];
    budgetSkips: Array<{from: string; action: RoleName; reason: string}>;
    guard: {blockedTotal: number; blocked: Record<string, number>; violations: string[]};
    emission?: EmissionRecord[];
};

export function writeTrace(dir: string, trace: Trace) {
    fs.mkdirSync(dir, {recursive: true});
    fs.writeFileSync(path.join(dir, 'trace.json'), `${JSON.stringify(trace, null, 2)}\n`);
    fs.writeFileSync(path.join(dir, 'trace.md'), renderTrace(trace));
}

export function readTrace(dir: string): Trace {
    const trace = JSON.parse(fs.readFileSync(path.join(dir, 'trace.json'), 'utf-8')) as Trace;
    if (trace.schema !== TRACE_SCHEMA) {
        throw new Error(`Unsupported trace schema: ${trace.schema}`);
    }
    return trace;
}

function stateLabel(trace: Trace, id: string): string {
    const state = trace.states.find((s) => s.id === id);
    return state ? `${id} ${state.pathname}` : id;
}

export function renderTrace(trace: Trace): string {
    const {limits, used} = trace.budget;
    const out: string[] = [
        '# Explorer trace',
        '',
        'Generated by `explorer-proto/src/cli.ts explore` (and `emit` for the last section). Deterministic: no ports, ids or timestamps.',
        '',
        `- Allowlist (exact role + name): ${trace.allowlist.map(describe).join('; ')}`,
        `- Budget: max ${limits.maxActions} actions, max depth ${limits.maxDepth}, max ${limits.maxStates} states.`,
        `- Used: ${used.actions} actions, ${used.states} states, deepest state at depth ${used.deepest}, ${used.budgetSkips} candidates left unexplored by the budget.`,
        `- Network guard (exploration): ${trace.guard.blockedTotal} requests blocked, ${trace.guard.violations.length} violations.`,
        ...Object.entries(trace.guard.blocked).map(([key, count]) => `  - blocked ${key}: ${count}`),
        ...trace.guard.violations.map((v) => `  - VIOLATION ${v}`),
        '',
        '## Roots',
        '',
        ...trace.roots.map((r) => `- navigate ${r.path} -> state ${r.state}`),
        '',
        '## Actions',
        '',
    ];
    for (const t of trace.transitions) {
        const note = t.note ? ` [${t.note}]` : '';
        out.push(
            `#${t.n} from ${stateLabel(trace, t.from)}: click ${describe(t.action)} -> ${t.changes.join(', ')} (state ${t.to})${note}`,
        );
    }
    if (trace.budgetSkips.length > 0) {
        out.push('', '## Budget skips', '');
        for (const s of trace.budgetSkips) {
            out.push(`- from ${s.from}: click ${describe(s.action)} skipped: budget (${s.reason})`);
        }
    }
    out.push('', '## States', '');
    for (const s of trace.states) {
        const via = s.via.length ? s.via.map((a) => `click ${describe(a)}`).join(' > ') : '(start)';
        out.push(`### ${s.id} (depth ${s.depth}, ${s.pathname})`, '');
        out.push(`- root: ${s.root}`, `- via: ${via}`);
        out.push(`- candidates: ${s.candidates.length ? s.candidates.map(describe).join('; ') : 'none'}`);
        if (s.allowlistedAbsent.length) {
            out.push(`- allowlisted but not present: ${s.allowlistedAbsent.map(describe).join('; ')}`);
        }
        const ambiguous = s.skipped.filter((k) => k.reason.includes('ambiguous'));
        const plain = s.skipped.filter((k) => !k.reason.includes('ambiguous'));
        for (const k of ambiguous) {
            out.push(`- skipped: ${describe(k)}: ${k.reason}`);
        }
        out.push(`- skipped (not allowlisted, ${plain.length}): ${plain.map(describe).join('; ')}`);
        out.push('');
    }
    if (trace.emission) {
        out.push('## Emission', '');
        for (const e of trace.emission) {
            out.push(`### ${e.scenario}: ${e.status}${e.file ? ` -> ${e.file}` : ''}`, '');
            if (e.path) {
                out.push(`- discovered path: ${e.path.join(' > ')}`);
            }
            out.push(...e.reasons.map((r) => `- ${r}`));
            out.push(...e.locatorChecks.map((c) => `- locator check: ${c}`));
            out.push('');
        }
    }
    return `${out.join('\n').trimEnd()}\n`;
}
