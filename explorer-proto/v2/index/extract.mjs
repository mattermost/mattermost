const HERE = path.dirname(fileURLToPath(import.meta.url));
export const TOOL_VERSION = '1';
export const DEFAULT_CACHE_ROOT = path.join(HERE, '.cache');

const isSource = (f) => /\.(ts|tsx|js|mjs)$/.test(f) && !/\.d\.ts$/.test(f);

export function extractorHash() {
    const files = [
        'extract.mjs',
        'fingerprint.mjs',
        'lib/constants.mjs',
        'lib/discover.mjs',
        'lib/repo.mjs',
        'lib/strings.mjs',
        'lib/ts.mjs',
        'lib/walker.mjs',
    ];
    return sha1(files.map((f) => fs.readFileSync(path.join(HERE, f), 'utf8')).join('\n')).slice(0, 8);
}

export function gitSha(root) {
    try {
        return execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], {
            encoding: 'utf8',
            stdio: ['ignore', 'pipe', 'ignore'],
        }).trim();
    } catch {
        return 'unknown';
    }
}

export function sourceRoots(root, {includeExplorer = true} = {}) {
    const cy = walkFiles(path.join(root, 'e2e-tests/cypress/tests/integration'), isSource).map((f) => ({
        abs: f,
        suite: 'cypress',
        origin: 'repo',
    }));
    const pw = [
        ...walkFiles(path.join(root, 'e2e-tests/playwright/specs'), isSource),
        ...walkFiles(path.join(root, 'e2e-tests/playwright/upgrade-specs'), isSource),
    ].map((f) => ({abs: f, suite: 'playwright', origin: 'repo'}));
    const explorer = [];
    if (includeExplorer) {
        const base = path.join(root, 'explorer-proto');
        const specs = (dir) => walkFiles(dir, (f) => /\.spec\.ts$/.test(f));
        explorer.push(...specs(path.join(base, 'generated')));
        const sessions = path.join(base, 'sessions');
        if (fs.existsSync(sessions)) {
            for (const d of fs.readdirSync(sessions).sort()) {
                explorer.push(...specs(path.join(sessions, d, 'generated')));
            }
        }
    }
    return [...cy, ...pw, ...explorer.map((f) => ({abs: f, suite: 'playwright', origin: 'session'}))];
}

function corpusHash(root, sources) {
    const files = new Set(sources.map((s) => s.abs));
    for (const f of walkFiles(path.join(root, 'e2e-tests/cypress/tests/support'), isSource)) {
        files.add(f);
    }
    for (const f of walkFiles(path.join(root, 'e2e-tests/playwright/lib/src'), isSource)) {
        files.add(f);
    }
    const parts = [...files]
        .map((f) => toPosix(path.relative(root, f)))
        .sort()
        .map((rel) => `${rel}\n${sha1(fs.readFileSync(path.join(root, rel), 'utf8'))}`);
    return sha1(parts.join('\n')).slice(0, 8);
}

function headerTags(text) {
    const tags = [];
    let stage;
    for (const m of text.matchAll(/^\s*\/\/\s*(Stage|Group):\s*(.*)$/gm)) {
        const found = m[2].match(/@[\w-]+/g) ?? [];
        if (m[1] === 'Stage') {
            stage = found[0];
        }
        tags.push(...found);
    }
    return {tags, stage};
}

function isEmittedMarker(info) {
    return /explorer-proto|@explorer_(pilot|session)|Generated by explorer/i.test(info.text.slice(0, 1500));
}

function tidy(list) {
    return [...new Set(list)].sort();
}

function layerLocals(scope, hookFns, fn) {
    const locals = new Map();
    for (const block of scope.blockNodes) {
        for (const [k, v] of collectLocals(block, false)) {
            locals.set(k, v);
        }
    }
    for (const h of hookFns) {
        for (const [k, v] of collectLocals(h, true)) {
            locals.set(k, v);
        }
    }
    if (fn) {
        for (const [k, v] of collectLocals(fn, true)) {
            locals.set(k, v);
        }
    }
    return locals;
}

function stampHook(col, before) {
    for (const key of ['actions', 'assertions', 'setup']) {
        for (let i = before[key]; i < col[key].length; i++) {
            col[key][i].phase = 'hook';
        }
    }
}

export function extractFile(repo, source) {
    const info = repo.file(source.abs);
    if (!info) {
        return {tests: [], hasTests: false};
    }
    const parseDiagnostics = info.sf.parseDiagnostics ?? [];
    const found = discoverTests(info, () => newCtx({repo, file: info, locals: new Map()}));
    const {tags: fileTags, stage} = source.suite === 'cypress' ? headerTags(info.text) : {tags: [], stage: undefined};
    const origin = source.origin === 'repo' && isEmittedMarker(info) ? 'emitted' : source.origin;
    const tests = [];
    for (const t of found) {
        const hookFns = [...t.scope.hooks.before, ...t.scope.hooks.beforeEach];
        const ctx = newCtx({repo, file: info, locals: layerLocals(t.scope, hookFns, t.fn)});
        const col = ctx.col;
        for (const h of hookFns) {
            const before = {actions: col.actions.length, assertions: col.assertions.length, setup: col.setup.length};
            const body = h.body;
            if (body && ts.isBlock(body)) {
                body.statements.forEach((st) => walkNode(st, ctx));
            } else if (body) {
                walkNode(body, ctx);
            }
            stampHook(col, before);
        }
        if (t.fn?.body) {
            if (ts.isBlock(t.fn.body)) {
                t.fn.body.statements.forEach((st) => walkNode(st, ctx));
            } else {
                walkNode(t.fn.body, ctx);
            }
        }
        const meta = leadingMeta(info, t.call);
        const titleText = t.title.text;
        const describe = t.scope.describe;
        const allTitles = [...describe, titleText].join(' ');
        const titleTags = allTitles.match(/@[\w-]+/g) ?? [];
        const mmIds = tidy((`${allTitles} ${meta.comments}`.match(/MM-T\d+(?:_\d+)?/g) ?? []).map((s) => s));
        const reasons = new Set(col.reasons);
        if (t.unresolved) {
            reasons.add('test_body_unresolved');
        }
        if (t.scope.loop && (t.title.dyn || t.scope.dynamicDescribe)) {
            reasons.add('loop_generated_test');
        }
        if (parseDiagnostics.length) {
            reasons.add('parse_error');
        }
        if (col.notes.has('event_cap_reached')) {
            reasons.add('event_cap_reached');
        }
        const real = (e) => e.phase !== 'hook';
        const direct = (e) => real(e) && !e.depth_limited;
        if (!col.actions.some(direct) && !col.assertions.some(direct)) {
            reasons.add(
                col.actions.some((e) => e.depth_limited) ? 'helper_depth_limit_only' : 'no_actions_or_assertions',
            );
        }
        const record = {
            id: `${info.rel}:${lineOf(info.sf, t.call)}`,
            suite: source.suite,
            origin,
            file: info.rel,
            line: lineOf(info.sf, t.call),
            end_line: info.sf.getLineAndCharacterOfPosition(t.call.getEnd()).line + 1,
            title: titleText,
            title_dynamic: t.title.dyn || undefined,
            describe,
            tags: tidy([...t.tags, ...titleTags, ...fileTags]),
            stage,
            mm_t_ids: mmIds,
            skipped: t.skipped || undefined,
            objective: meta.objective,
            narrative: narrativeOf(info, t.fn),
            actors: {count: col.actors.size, keys: [...col.actors.keys()].sort()},
            setup: col.setup,
            actions: col.actions,
            assertions: col.assertions,
            locators: [...col.locators].sort(),
            source_status: reasons.size ? 'partial' : 'extracted',
            partial_reasons: [...reasons].sort(),
            notes: [...col.notes].filter((n) => n !== 'event_cap_reached').sort(),
        };
        Object.assign(record, fingerprintOf(record));
        for (const k of Object.keys(record)) {
            if (record[k] === undefined) {
                delete record[k];
            }
        }
        tests.push(record);
    }
    return {tests, hasTests: found.length > 0, parseErrors: parseDiagnostics.length};
}

export function extractRepo({root = DEFAULT_REPO_ROOT, includeExplorer = true, sha} = {}) {
    const repo = new RepoIndex(root);
    repo.build();
    const sources = sourceRoots(root, {includeExplorer}).sort((a, b) => compareStr(toPosix(a.abs), toPosix(b.abs)));
    const tests = [];
    let filesWithTests = 0;
    let parseErrors = 0;
    for (const s of sources) {
        const r = extractFile(repo, s);
        parseErrors += r.parseErrors ? 1 : 0;
        if (r.hasTests) {
            filesWithTests += 1;
        }
        tests.push(...r.tests);
    }
    tests.sort((a, b) => compareStr(a.file, b.file) || a.line - b.line);
    return {tests, meta: buildMeta(root, sources, tests, filesWithTests, parseErrors, sha)};
}

function count(list, key) {
    const m = {};
    for (const x of list) {
        const k = key(x);
        m[k] = (m[k] ?? 0) + 1;
    }
    return Object.fromEntries(Object.entries(m).sort(([a], [b]) => (a < b ? -1 : 1)));
}

function buildMeta(root, sources, tests, filesWithTests, parseErrors, shaOverride) {
    const reasons = {};
    const categories = {};
    for (const t of tests) {
        for (const r of t.partial_reasons) {
            reasons[r] = (reasons[r] ?? 0) + 1;
            const cat = r.split(':')[0];
            categories[cat] = (categories[cat] ?? 0) + 1;
        }
    }
    const sortByCount = (o) =>
        Object.fromEntries(Object.entries(o).sort(([ka, a], [kb, b]) => b - a || (ka < kb ? -1 : 1)));
    const fp = {};
    for (const t of tests) {
        (fp[t.fingerprint] ??= []).push(t.id);
    }
    const duplicateGroups = Object.values(fp).filter((g) => g.length > 1);
    const sha = shaOverride ?? gitSha(root);
    const corpus = corpusHash(root, sources);
    const ext = extractorHash();
    return {
        tool_version: TOOL_VERSION,
        cache_key: `${sha.slice(0, 12)}-${corpus}-${ext}`,
        git_sha: sha,
        corpus_hash: corpus,
        extractor_hash: ext,
        counts: {
            files_scanned: sources.length,
            files_with_tests: filesWithTests,
            files_with_parse_diagnostics: parseErrors,
            tests: tests.length,
            by_suite: count(tests, (t) => t.suite),
            by_origin: count(tests, (t) => t.origin),
            files_with_tests_by_suite: count(
                [...new Set(tests.map((t) => `${t.suite}|${t.file}`))],
                (k) => k.split('|')[0],
            ),
            source_status: count(tests, (t) => t.source_status),
            skipped: tests.filter((t) => t.skipped).length,
        },
        partial_reason_categories: sortByCount(categories),
        partial_reasons: sortByCount(reasons),
        duplicate_fingerprint_groups: duplicateGroups.length,
        tests_in_duplicate_fingerprint_groups: duplicateGroups.reduce((n, g) => n + g.length, 0),
    };
}

export function writeIndex(outDir, {tests, meta}) {
    fs.mkdirSync(outDir, {recursive: true});
    fs.writeFileSync(path.join(outDir, 'tests.jsonl'), `${tests.map((t) => JSON.stringify(t)).join('\n')}\n`);
    fs.writeFileSync(path.join(outDir, 'meta.json'), `${JSON.stringify(meta, null, 2)}\n`);
}

export function loadIndex(dir) {
    const meta = JSON.parse(fs.readFileSync(path.join(dir, 'meta.json'), 'utf8'));
    const tests = fs
        .readFileSync(path.join(dir, 'tests.jsonl'), 'utf8')
        .split('\n')
        .filter(Boolean)
        .map((l) => JSON.parse(l));
    return {tests, meta};
}

export function defaultIndexDir(root = DEFAULT_REPO_ROOT, includeExplorer = true) {
    const sources = sourceRoots(root, {includeExplorer});
    return path.join(
        DEFAULT_CACHE_ROOT,
        `${gitSha(root).slice(0, 12)}-${corpusHash(root, sources)}-${extractorHash()}`,
    );
}

export function ensureIndex(dir, opts = {}) {
    if (dir && fs.existsSync(path.join(dir, 'meta.json'))) {
        return dir;
    }
    const target = dir ?? defaultIndexDir(opts.root);
    if (!fs.existsSync(path.join(target, 'meta.json'))) {
        writeIndex(target, extractRepo(opts));
    }
    return target;
}

function parseArgs(argv) {
    const args = {};
    for (const a of argv) {
        const m = /^--([\w-]+)(?:=(.*))?$/.exec(a);
        if (m) {
            args[m[1]] = m[2] ?? true;
        }
    }
    return args;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const args = parseArgs(process.argv.slice(2));
    const root = args['repo-root'] ? path.resolve(args['repo-root']) : DEFAULT_REPO_ROOT;
    const started = Date.now();
    const result = extractRepo({
        root,
        includeExplorer: !args['no-explorer'],
        sha: typeof args.sha === 'string' ? args.sha : undefined,
    });
    const out = args.out ? path.resolve(args.out) : defaultIndexDir(root, !args['no-explorer']);
    writeIndex(out, result);
    const c = result.meta.counts;
    process.stderr.write(
        `extracted ${c.tests} tests from ${c.files_with_tests}/${c.files_scanned} files in ${((Date.now() - started) / 1000).toFixed(1)}s ` +
            `(extracted=${c.source_status.extracted ?? 0}, partial=${c.source_status.partial ?? 0})\n`,
    );
    process.stdout.write(`${path.relative(process.cwd(), out) || '.'}\n`);
}
