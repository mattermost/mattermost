import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {fingerprintOf, sha1} from './fingerprint.mjs';
import {discoverTests, leadingMeta, narrativeOf} from './lib/discover.mjs';
import {RepoIndex, toPosix, walkFiles} from './lib/repo.mjs';
import {compareStr} from './lib/strings.mjs';
import {DEFAULT_REPO_ROOT, lineOf, ts} from './lib/ts.mjs';
