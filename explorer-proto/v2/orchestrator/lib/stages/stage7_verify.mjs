// Stage 7, verify: run every registered deterministic gate on each accepted charter, then ask a verifier agent for an
// independent equivalence and leak review. The agent's result schema is generated per task so that its proposed
// overall can never be "pass" while a deterministic gate is fail or blocked. The agent can add a failing gate; it can
// never remove or soften one.
import fs from 'node:fs';
import path from 'node:path';

import {acceptedCharters, dirDigest} from './util.mjs';

import {GATES} from '../../gates/index.mjs';
import {BudgetExceeded} from '../budgets.mjs';
import {readJson, slug} from '../common.mjs';
import {buildVerdict, outcomeOf, overallOf} from '../verdicts.mjs';

const AGENT_RESULTS_ID = 'https://explorer-proto.invalid/v2/orchestrator/agent-results.schema.json';

export function allowedOverall(deterministic) {
    return {pass: ['pass', 'fail'], blocked: ['blocked', 'fail'], fail: ['fail']}[deterministic];
}

/** The per-task result schema: the base verify format plus one constraint per charter. */
export function verifyResultSchema(items) {
    const selector = (id) => ({properties: {charter_id: {const: id}}, required: ['charter_id']});
    return {
        $comment:
            'Generated by the orchestrator for one verify task. proposed_overall is limited by the deterministic gates.',
        allOf: [
            {$ref: `${AGENT_RESULTS_ID}#/definitions/verify`},
            {
                properties: {
                    reviews: {
                        minItems: items.length,
                        maxItems: items.length,
                        allOf: items.map((i) => ({contains: selector(i.charterId)})),
                        items: {
                            allOf: items.map((i) => ({
                                if: selector(i.charterId),
                                then: {properties: {proposed_overall: {enum: allowedOverall(i.deterministic)}}},
                            })),
                        },
                    },
                },
            },
        ],
    };
}

function checkVerifyConsistency(result) {
    const errors = [];
    for (const r of result.reviews) {
        const leaky = r.equivalence === 'equivalent' || r.leak_review === 'leaks';
        if (r.proposed_overall === 'fail' && !leaky) {
            errors.push(`/reviews/${r.charter_id}/proposed_overall: fail needs an equivalent spec or a leak finding`);
        }
        if (r.proposed_overall === 'pass' && leaky) {
            errors.push(`/reviews/${r.charter_id}/proposed_overall: pass contradicts the review findings`);
        }
    }
    return errors;
}

function gateContext(ctx, item) {
    const s = slug(item.id);
    const specRel = `6-emit/specs/${s}.spec.ts`;
    const selection = ctx.readJson(4, 'selection.json', 'orch#selection');
    return {
        out: ctx.out,
        flags: ctx.flags,
        live: ctx.flags.live,
        charterId: item.id,
        slug: s,
        charter: item.charter,
        charterFile: item.file,
        decision: selection.decisions.find((d) => d.charter_id === item.id),
        specs: fs.existsSync(path.join(ctx.out, specRel)) ? [{rel: specRel, abs: path.join(ctx.out, specRel)}] : [],
        readOut: (rel) => readJson(path.join(ctx.out, rel)),
        exec: (argv, options) => ctx.exec(argv, options),
    };
}

async function runGates(ctx, item) {
    const gctx = gateContext(ctx, item);
    const results = [];
    for (const gate of GATES) {
        if (gate.liveOnly && !ctx.flags.live) {
            results.push({
                gate: gate.gate,
                result: 'blocked',
                blocked_reason: 'environment',
                evidence: [{kind: 'report', ref: item.file}],
            });
            continue;
        }
        try {
            results.push({gate: gate.gate, ...(await gate.run(gctx))});
        } catch (e) {
            if (e instanceof BudgetExceeded) {
                throw e;
            }
            results.push({gate: gate.gate, result: 'fail', evidence: [{kind: 'log', ref: item.file}]});
        }
    }
    return results;
}

export default {
    index: 7,
    name: 'verify',
    modes: ['author', 'both'],

    inputs(ctx) {
        return [
            {target: dirDigest(ctx, 0)},
            {select: dirDigest(ctx, 4)},
            {discover: dirDigest(ctx, 5)},
            {emit: dirDigest(ctx, 6)},
            {repeat: ctx.flags.repeat ?? null},
        ];
    },

    async run(ctx) {
        const selection = ctx.readJson(4, 'selection.json', 'orch#selection');
        const accepted = acceptedCharters(ctx);
        const summary = {
            schema: 'explorer-verify-summary/v1',
            live: ctx.flags.live,
            gates: GATES.map((g) => g.id),
            verdicts: [],
        };
        const bakeoff = ctx.feature.bakeoff_feature;

        for (const d of selection.decisions.filter((x) => x.decision !== 'accepted')) {
            const verdict = ctx.readJson(4, d.verdict_file.replace(/^4-select\//, ''), 'verdict');
            const file = `verdicts/${path.basename(d.verdict_file)}`;
            ctx.writeJson(file, verdict, 'verdict');
            summary.verdicts.push({
                charter_id: d.charter_id,
                overall: verdict.overall,
                outcome: verdict.outcome,
                file: ctx.stageRel(file),
            });
        }

        const gateSets = [];
        for (const item of accepted) {
            const gates = await runGates(ctx, item);
            gateSets.push({item, gates});
            ctx.writeJson(
                `gates/${slug(item.id)}.json`,
                {schema: 'explorer-gate-results/v1', charter_id: item.id, gates},
                'orch#gate-results',
            );
        }

        let reviews = [];
        if (gateSets.length) {
            const items = gateSets.map((g) => ({charterId: g.item.id, deterministic: overallOf(g.gates)}));
            const result = await ctx.agent({
                role: 'verifier',
                prompt: 'verify.md',
                inputs: gateSets.flatMap((g) => [
                    {
                        path: ctx.stageRel(`gates/${slug(g.item.id)}.json`),
                        base: 'out',
                        purpose: `deterministic gate results for ${g.item.id}`,
                    },
                    {path: g.item.file, base: 'out', purpose: `accepted charter ${g.item.id}`},
                ]),
                dynamicSchema: verifyResultSchema(items),
                check: checkVerifyConsistency,
            });
            reviews = result.reviews;
        }

        for (const {item, gates} of gateSets) {
            const review = reviews.find((r) => r.charter_id === item.id);
            const all = [...gates];
            if (review.equivalence === 'equivalent') {
                all.push({gate: 'duplicate', result: 'fail', evidence: review.evidence});
            }
            if (review.leak_review === 'leaks') {
                all.push({gate: 'leakage', result: 'fail', evidence: review.evidence});
            }
            const overall = overallOf(all);
            const outcome = overall === 'fail' ? 'failed' : outcomeOf(overall);
            const verdict = buildVerdict({subjectId: item.id, outcome, gates: all, bakeoffFeature: bakeoff});
            const file = `verdicts/${slug(item.id)}.verdict.json`;
            ctx.writeJson(file, verdict, 'verdict');
            summary.verdicts.push({
                charter_id: item.id,
                overall: verdict.overall,
                outcome: verdict.outcome,
                file: ctx.stageRel(file),
            });
        }

        summary.verdicts.sort((a, b) => (a.charter_id < b.charter_id ? -1 : 1));
        ctx.writeJson('verify-summary.json', summary, 'orch#verify-summary');

        const failed = summary.verdicts.filter((v) => v.outcome === 'failed');
        const blocked = summary.verdicts.filter((v) => v.overall === 'blocked');
        if (failed.length) {
            return {result: 'fail', reason: `${failed.length} charter(s) failed verification`};
        }
        if (blocked.length) {
            return ctx.flags.live
                ? {result: 'blocked', reason: `${blocked.length} charter(s) blocked: a gate could not run`}
                : {
                      result: 'skipped',
                      reason: 'skipped: dry run, gates that need a live stack or an emitted spec are blocked',
                  };
        }
        return {result: 'pass', reason: `${summary.verdicts.length} verdict(s) written`};
    },
};
