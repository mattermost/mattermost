package main

import (
	"flag"
	"fmt"
	"os"
	"slices"
	"strings"

	"github.com/mattermost/mattermost/server/public/model"
)

func main() {
	out := flag.String("out", "", "path of the TypeScript file to write")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "-out is required")
		os.Exit(1)
	}

	var flags model.FeatureFlags
	flags.SetDefaults()
	values := flags.ToMap()

	names := make([]string, 0, len(values))
	for name := range values {
		names = append(names, name)
	}
	slices.Sort(names)

	var b strings.Builder
	b.WriteString("// Copyright (c) 2015-present Mattermost, Inc. All Rights Reserved.\n")
	b.WriteString("// See LICENSE.txt for license information.\n\n")
	b.WriteString("// Code generated by default_feature_flags_generator. DO NOT EDIT.\n\n")
	b.WriteString("export const defaultFeatureFlags: Record<string, string> = {\n")
	for _, name := range names {
		fmt.Fprintf(&b, "    %s: '%s',\n", name, values[name])
	}
	b.WriteString("};\n")

	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
