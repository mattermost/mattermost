import {screen, waitFor} from '@testing-library/dom';
import userEvent from '@testing-library/user-event';
import React from 'react';

import {WithTooltip} from './with_tooltip';

import {renderWithContext} from '../../testing';

jest.mock('@mattermost/shared/utils/user_agent', () => ({
    isMac: jest.fn().mockReturnValue(false),
}));

describe('WithTooltip', () => {
    test('renders children correctly', async () => {
        renderWithContext(
            <WithTooltip title='TooltipOfButton'>
                <button>{'I am a button surrounded by a tooltip'}</button>
            </WithTooltip>,
        );

        expect(screen.getByText('I am a button surrounded by a tooltip')).toBeInTheDocument();
    });

    test('shows tooltip on hover', async () => {
        jest.useFakeTimers();

        renderWithContext(
            <WithTooltip title='Tooltip will appear on hover'>
                <div>{'Hover Me'}</div>
            </WithTooltip>,
        );

        await userEvent.hover(screen.getByText('Hover Me'), {advanceTimers: jest.advanceTimersByTime});

        await waitFor(() => {
            expect(screen.getByText('Tooltip will appear on hover')).toBeInTheDocument();
        });
    });

    test('shows tooltip on focus', async () => {
        jest.useFakeTimers();

        renderWithContext(
            <WithTooltip title='Tooltip will appear on hover'>
                <button>{'Hover Me'}</button>
            </WithTooltip>,
        );

        const trigger = screen.getByText('Hover Me');

        // Clicking the button will simulate a focus event
        await userEvent.click(trigger, {advanceTimers: jest.advanceTimersByTime});

        await waitFor(() => {
            expect(trigger).toHaveFocus();
            expect(screen.getByText('Tooltip will appear on hover')).toBeInTheDocument();
        });
    });

    test('calls onOpen when tooltip appears', async () => {
        const onOpen = jest.fn();

        jest.useFakeTimers();

        renderWithContext(
            <WithTooltip
                title='Tooltip will appear on hover'
                onOpen={onOpen}
            >
                <div>{'Hover Me'}</div>
            </WithTooltip>,
        );

        expect(onOpen).not.toHaveBeenCalled();

        await userEvent.hover(screen.getByText('Hover Me'), {advanceTimers: jest.advanceTimersByTime});

        await waitFor(() => {
            expect(screen.getByText('Tooltip will appear on hover')).toBeInTheDocument();
            expect(onOpen).toHaveBeenCalled();
        });
    });

    describe('aria wiring', () => {
        // These use real timers because the tooltip only mounts after the hover delays elapse, and
        // advancing fake timers by hand does not flush the resulting React state updates. The tests
        // above install fake timers without restoring them, so undo that here.
        beforeEach(() => {
            jest.useRealTimers();
        });

        async function openTooltip(extraProps: {id?: string} = {}) {
            const user = userEvent.setup();

            renderWithContext(
                <WithTooltip
                    title='Save the thing'
                    {...extraProps}
                >
                    <button aria-label='Save the thing'>{'X'}</button>
                </WithTooltip>,
            );

            const trigger = screen.getByLabelText('Save the thing');
            await user.hover(trigger);
            await waitFor(() => expect(screen.getByRole('tooltip')).toBeInTheDocument(), {timeout: 4000});

            return trigger;
        }

        test('aria-describedby on the trigger resolves to the tooltip', async () => {
            const trigger = await openTooltip();

            const describedBy = trigger.getAttribute('aria-describedby');
            expect(describedBy).toBeTruthy();

            // Regression guard: rendering the floating element with `id={undefined}` used to strip
            // the id generated by floating-ui, leaving this reference dangling so that assistive
            // technology had nothing to announce (WCAG 2.1 SC 1.3.1).
            expect(document.getElementById(describedBy!)).toBe(screen.getByRole('tooltip'));
        });

        test('an explicitly passed id is honoured and still resolves', async () => {
            const trigger = await openTooltip({id: 'my-custom-id'});

            expect(screen.getByRole('tooltip')).toHaveAttribute('id', 'my-custom-id');
            expect(document.getElementById(trigger.getAttribute('aria-describedby')!)).toBe(screen.getByRole('tooltip'));
        });
    });
});
